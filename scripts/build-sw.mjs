// Runs after `next build`: writes out/sw.js, the service worker that keeps a
// copy of the whole app on the device so it works with no internet.
//
// Every page, script, style, font and icon of the export is stored on the
// first visit (about 7 MB, less over the wire). The cache name carries a hash
// of all the files, so each new build installs as a new version and the old
// copy is removed only after the user accepts the update.

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const OUT = "out";

// Legacy font format (every supported browser takes woff2), and maps.
const SKIP = [/\.woff$/, /\.map$/, /^sw\.js$/];

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = walk(OUT)
  .map((path) => relative(OUT, path).split(sep).join("/"))
  .filter((rel) => !SKIP.some((re) => re.test(rel)))
  .sort();

const hash = createHash("sha256");
for (const rel of files) hash.update(rel).update(readFileSync(join(OUT, rel)));
const version = hash.digest("hex").slice(0, 12);

// Pages are stored under their address ("/tools/clock/"), not "index.html".
const urls = files.map((rel) => "/" + (rel === "index.html" ? "" : rel.replace(/(^|\/)index\.html$/, "$1")));

const sw = `// Generated by scripts/build-sw.mjs; do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = "tizhooshan-" + VERSION;
const FILES = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("tizhooshan-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// The page asks for this when the user presses the update button.
self.addEventListener("message", (event) => {
  if (event.data === "skipWaiting") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(respond(request, url));
});

async function respond(request, url) {
  const cache = await caches.open(CACHE);
  let path = url.pathname;
  // "/tools/clock" is the same page as "/tools/clock/".
  if (request.mode === "navigate" && !path.endsWith("/") && !path.split("/").pop().includes(".")) path += "/";
  // Stored copies first; the query (Next's ?_rsc=…) never changes the file.
  const hit = await cache.match(path, { ignoreSearch: true });
  if (hit) return hit;
  try {
    return await fetch(request);
  } catch (error) {
    if (request.mode === "navigate") {
      const notFound = await cache.match("/404.html");
      if (notFound) return notFound;
    }
    throw error;
  }
}
`;

writeFileSync(join(OUT, "sw.js"), sw);
const bytes = files.reduce((sum, rel) => sum + statSync(join(OUT, rel)).size, 0);
console.log(`sw.js: version ${version}, ${files.length} files, ${(bytes / 1048576).toFixed(1)} MB`);
